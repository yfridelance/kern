// The selection is curated for homelab tools; add a [name, slug] pair and run `npm run brands`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkgDir = join(root, 'node_modules/simple-icons');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const data = new Map(JSON.parse(readFileSync(join(pkgDir, 'data/simple-icons.json'), 'utf8')).map((i) => [i.slug, i]));

/** [Kern name without `brand-`, Simple Icons slug] */
const BRANDS = [
  ['home-assistant', 'homeassistant'],
  ['zigbee', 'zigbee'],
  ['mqtt', 'mqtt'],
  ['shelly', 'shelly'],
  ['tasmota', 'tasmota'],
  ['esphome', 'esphome'],
  ['espressif', 'espressif'],
  ['node-red', 'nodered'],
  ['homebridge', 'homebridge'],
  ['philips-hue', 'philipshue'],
  ['ikea', 'ikea'],
  ['google-home', 'googlehome'],
  ['bluetooth', 'bluetooth'],
  ['grafana', 'grafana'],
  ['influxdb', 'influxdb'],
  ['docker', 'docker'],
  ['proxmox', 'proxmox'],
  ['raspberry-pi', 'raspberrypi'],
  ['arduino', 'arduino'],
  ['linux', 'linux'],
  ['debian', 'debian'],
  ['ubuntu', 'ubuntu'],
  ['openwrt', 'openwrt'],
  ['pi-hole', 'pihole'],
  ['ubiquiti', 'ubiquiti'],
  ['synology', 'synology'],
  ['tailscale', 'tailscale'],
  ['wireguard', 'wireguard'],
  ['cloudflare', 'cloudflare'],
  ['nextcloud', 'nextcloud'],
  ['plex', 'plex'],
  ['github', 'github'],
  ['gitlab', 'gitlab'],
  ['google', 'google'],
  ['apple', 'apple'],
  ['android', 'android'],
  ['telegram', 'telegram'],
  ['signal', 'signal'],
  ['whatsapp', 'whatsapp'],
];

const lines = BRANDS.map(([name, slug]) => {
  const meta = data.get(slug);
  if (!meta) throw new Error(`simple-icons ${version} has no "${slug}"`);
  const svg = readFileSync(join(pkgDir, 'icons', `${slug}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${slug}: expected one path, got ${paths.length}`);
  return `  'brand-${name}': { title: ${JSON.stringify(meta.title)}, hex: '#${meta.hex.toLowerCase()}', path: '${paths[0]}' },`;
});

writeFileSync(
  join(root, 'src/utils/brands.ts'),
  `// Generated by scripts/build-brands.mjs from simple-icons ${version} (CC0-1.0) – do not edit.
// The logos are trademarks of their owners; use them to refer to the product and follow the owners' guidelines.

/** Brand icons for kern-icon: 24px viewBox, one filled path; \`hex\` is the official colour. */
export const BRANDS = {
${lines.join('\n')}
} as const;

export type BrandName = keyof typeof BRANDS;

/** All brand icon names (\`brand-…\`). */
export const BRAND_NAMES = Object.keys(BRANDS) as BrandName[];
`,
);
console.log(`brands: ${BRANDS.length} icons from simple-icons ${version} → src/utils/brands.ts`);
