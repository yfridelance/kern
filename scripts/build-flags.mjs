// Country flags for kern-icon (`flag-*`) from flag-icons (MIT): node scripts/build-flags.mjs
// → src/utils/flag-names.ts (names), src/utils/flags.ts (loaders) and src/utils/flags/<code>.ts (one module per flag,
// so an app loads only the flags it shows). The selection covers the usual UI languages; add a code and run `npm run flags`.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkgDir = join(root, 'node_modules/flag-icons');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

/** ISO 3166-1 alpha-2 codes, lower case. */
const FLAGS = ['ch', 'li', 'de', 'at', 'fr', 'it', 'gb', 'us', 'ie', 'es', 'pt', 'nl', 'be', 'lu', 'dk', 'se', 'no', 'fi', 'is', 'pl', 'cz', 'sk', 'hu', 'si', 'hr', 'ro', 'bg', 'gr', 'tr', 'ua', 'jp', 'cn', 'kr', 'br'];

const regions = new Intl.DisplayNames(['en'], { type: 'region' });
const header = `// Generated by scripts/build-flags.mjs from flag-icons ${version} (MIT, https://github.com/lipis/flag-icons) – do not edit.`;

const outDir = join(root, 'src/utils/flags');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir);

for (const code of FLAGS) {
  const svg = readFileSync(join(pkgDir, 'flags/4x3', `${code}.svg`), 'utf8');
  const m = /^<svg[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg.trim());
  if (!m) throw new Error(`${code}: unexpected SVG`);
  // Ids stay: every kern-icon has its own shadow root, so ids of two flags never meet.
  const body = m[2].replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();
  writeFileSync(
    join(outDir, `${code}.ts`),
    `${header}

export default { title: ${JSON.stringify(regions.of(code.toUpperCase()))}, viewBox: '${m[1]}', body: ${JSON.stringify(body)} };
`,
  );
}

const names = FLAGS.map((c) => `flag-${c}`);

writeFileSync(
  join(root, 'src/utils/flag-names.ts'),
  `${header}

/** All flag icon names (\`flag-ch\` …, ISO 3166 country codes); the drawings load on demand from flags/. */
export const FLAG_NAMES = ${JSON.stringify(names, null, 2).replace(/"/g, "'")} as const;

export type FlagName = (typeof FLAG_NAMES)[number];
`,
);

writeFileSync(
  join(root, 'src/utils/flags.ts'),
  `${header}

import type { FlagName } from './flag-names';

/** A flag: multi-coloured SVG content in a 4:3 viewBox. */
export interface Flag {
  title: string;
  viewBox: string;
  body: string;
}

/** One import per flag, so a page loads only the flags it shows. */
export const FLAGS: Record<FlagName, () => Promise<Flag>> = {
${FLAGS.map((c) => `  'flag-${c}': () => import('./flags/${c}').then((m) => m.default),`).join('\n')}
};
`,
);
console.log(`flags: ${FLAGS.length} flags from flag-icons ${version} → src/utils/flag-names.ts, flags.ts, flags/`);
